create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role text not null default 'customer'
    check (role in ('customer','admin','delivery')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  category text not null default 'General',
  price numeric(12,2) not null check (price >= 0),
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  size text not null,
  color text not null,
  stock integer not null default 0 check (stock >= 0),
  unique(product_id,size,color)
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id),
  delivery_id uuid references public.profiles(id),
  status text not null default 'pending'
    check (status in ('pending','confirmed','preparing','on_the_way','delivered','cancelled')),
  delivery_address text,
  total numeric(12,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  variant_id bigint not null references public.product_variants(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status text not null,
  changed_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_products_active on public.products(active);
create index if not exists idx_variants_product on public.product_variants(product_id);
create index if not exists idx_orders_customer on public.orders(customer_id);
create index if not exists idx_orders_delivery on public.orders(delivery_id);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.product_variants enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_status_history enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin'); $$;

drop policy if exists "profiles read own" on public.profiles;
create policy "profiles read own" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles update own basic" on public.profiles;
create policy "profiles update own basic" on public.profiles for update to authenticated
using (id=auth.uid()) with check (id=auth.uid() and role <> 'admin');

drop policy if exists "products public read active" on public.products;
create policy "products public read active" on public.products for select to anon, authenticated
using (active = true or public.is_admin());

drop policy if exists "variants public read" on public.product_variants;
create policy "variants public read" on public.product_variants for select to anon, authenticated
using (exists(select 1 from public.products pr where pr.id=product_id and (pr.active=true or public.is_admin())));

drop policy if exists "orders customer read own" on public.orders;
create policy "orders customer read own" on public.orders for select to authenticated
using (customer_id=auth.uid() or delivery_id=auth.uid() or public.is_admin());

drop policy if exists "order items read authorized order" on public.order_items;
create policy "order items read authorized order" on public.order_items for select to authenticated
using (exists(select 1 from public.orders o where o.id=order_id and (o.customer_id=auth.uid() or o.delivery_id=auth.uid() or public.is_admin())));

drop policy if exists "history read authorized order" on public.order_status_history;
create policy "history read authorized order" on public.order_status_history for select to authenticated
using (exists(select 1 from public.orders o where o.id=order_id and (o.customer_id=auth.uid() or o.delivery_id=auth.uid() or public.is_admin())));

-- Crear automáticamente perfil básico al registrar usuario.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id, full_name)
  values(new.id, coalesce(new.raw_user_meta_data->>'full_name',''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Crear pedido y descontar stock de forma transaccional.
create or replace function public.create_order(p_address text, p_items jsonb)
returns bigint
language plpgsql security definer
set search_path=public
as $$
declare
  v_order_id bigint;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_variant_id bigint;
  v_qty integer;
  v_price numeric(12,2);
  v_stock integer;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then
    raise exception 'El pedido no contiene productos';
  end if;

  insert into public.orders(customer_id, delivery_address, total)
  values(auth.uid(), nullif(trim(p_address),''), 0)
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_variant_id := (v_item->>'variant_id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 or v_qty > 50 then raise exception 'Cantidad no válida'; end if;

    select pv.stock, pr.price into v_stock, v_price
    from public.product_variants pv join public.products pr on pr.id=pv.product_id
    where pv.id=v_variant_id and pr.active=true for update of pv;

    if not found then raise exception 'Variante no disponible'; end if;
    if v_stock < v_qty then raise exception 'Inventario insuficiente'; end if;

    update public.product_variants set stock=stock-v_qty where id=v_variant_id;
    insert into public.order_items(order_id, variant_id, quantity, unit_price)
    values(v_order_id, v_variant_id, v_qty, v_price);
    v_total := v_total + v_price*v_qty;
  end loop;

  update public.orders set total=v_total where id=v_order_id;
  insert into public.order_status_history(order_id,status,changed_by)
  values(v_order_id,'pending',auth.uid());
  return v_order_id;
end;
$$;

grant execute on function public.create_order(text,jsonb) to authenticated;
grant execute on function public.is_admin() to authenticated;
